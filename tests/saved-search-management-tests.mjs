import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
const source=await fs.readFile(new URL('../frontend/app.js',import.meta.url),'utf8');
let markup='',title='',confirm,deleted=[],renders=0,stashes=0;
const elements={'utility-body':{}};
const state={searches:[{id:'s1',name:'My project search'}],folders:[{id:'f1',name:'Private folder'}],tags:[{id:'t1',name:'Private tag'}],notes:new Map([['n1',{id:'n1',content:'Keep this note'}]])};
const ctx=vm.createContext({state,$:id=>elements[id],escape:v=>String(v),icon:()=>'<svg></svg>',handle:fn=>fn,onlineOnly(){},dialog(t,html){title=t;markup=html;},confirmDialog(t,message,callback){assert.match(message,/notes will be kept/);confirm=callback;},api:async(path,method)=>{if(method==='DELETE'){deleted.push(path);return{};}return{searches:[]};},render(){renders++;},stash:async()=>{stashes++;},notify(){},readEditor(){throw Error('saved-search deletion must not touch editor');},synchronize(){throw Error('saved-search deletion must not sync notes');}});
vm.runInContext(source.slice(source.indexOf('function removeOrganization('),source.indexOf('function renameOrganization(')),ctx);
vm.runInContext(source.slice(source.indexOf('function organizationDialog('),source.indexOf('async function restoreFile(')),ctx);
ctx.organizationDialog();
assert.equal(title,'Manage saved searches');
assert.match(markup,/Delete saved search My project search/);
assert.ok(!markup.includes('Private folder')&&!markup.includes('Private tag'));
const notes=JSON.stringify([...state.notes]);
elements['utility-body'].onclick({target:{closest:()=>({dataset:{removeSearch:'s1'}})}});
await confirm();
assert.deepEqual(deleted,['/searches/s1']);
assert.equal(state.searches.length,0);assert.equal(JSON.stringify([...state.notes]),notes);
assert.equal(state.folders.length,1);assert.equal(state.tags.length,1);assert.ok(renders&&stashes);
ctx.organizationDialog();assert.match(markup,/No saved searches yet/);
assert.ok(!source.includes('$("saved-nav")'));
console.log('PASS: settings manages saved searches only; deletion keeps notes, tags, folders and editor unchanged; sidebar list removed');
